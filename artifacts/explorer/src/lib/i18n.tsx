type Translations = typeof translations.en;

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translations;
}

const I18nContext = createContext<I18nContextValue>({
  lang: "en",
  setLang: () => {},
  t: translations.en,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const saved = (typeof localStorage !== "undefined" ? localStorage.getItem("apr-lang") : null) as Lang | null;
  const [lang, setLangState] = useState<Lang>(saved ?? "en");

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("apr-lang", l);
  }, []);

  return (
    <I18nContext.Provider value={{ lang, setLang, t: translations[lang] as Translations }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

